# v (118) = 1312 (Base4) -> 404 985 404 996
# 推导：404=1, 985=3, 996=2, 剩下251=0

cipher_text = "404 985 404 996 404 996 985 404 404 996 251 985 404 985 996 985 404 251 996 996 404 996 996 404 404 404 985 985 404 251 404 251 404 996 404 404 251 985 251 404 404 404 985 985 404 404 251 985 404 985 404 404 251 985 251 404 404 404 985 985 404 985 251 985 404 251 996 251 404 996 404 404 404 996 985 996 404 404 985 985 404 404 996 251 251 985 251 404 404 996 404 404 404 404 985 985 404 996 404 251 404 251 251 404 404 996 996 404 404 404 985 985 404 251 985 251 404 985 404 404 404 404 985 985 404 985 996 404 404 996 996 404 404 996 985 996 404 404 985 985 404 996 251 996 404 996 996 404 404 985 985 404"

# 严格映射
mapping = {
    '251': 0,
    '404': 1,
    '996': 2,
    '985': 3
}

tokens = cipher_text.split()
result = ""

print(f"Token总数: {len(tokens)}")
print("--- 开始解码 ---")

for i in range(0, len(tokens), 4):
    chunk = tokens[i:i + 4]
    if len(chunk) < 4: break

    # Base4 转 ASCII
    # value = d1*64 + d2*16 + d3*4 + d4
    try:
        val = (mapping[chunk[0]] * 64 +
               mapping[chunk[1]] * 16 +
               mapping[chunk[2]] * 4 +
               mapping[chunk[3]])

        result += chr(val)
        # 打印调试信息：看看每组解出来是什么
        # print(f"组{i//4+1}: {chunk} -> {val} ('{chr(val)}')")

    except KeyError as e:
        print(f"错误: 发现未知数字 {e}")

print("最终结果:", result)